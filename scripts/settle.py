"""Settle the ledger against real outcomes and write down what we learned.

Run after matches finish::

    PYTHONPATH=. .venv/bin/python scripts/settle.py
    PYTHONPATH=. .venv/bin/python scripts/settle.py --lessons

This closes the loop the whole project depends on.  Without it we accumulate
predictions and never find out which families were worth making, which is how
the predecessor event lost 125 relative points on fouls before anyone noticed
the crowd was better than every model there.  The correct response to that was
not "model fouls harder", it was "stop departing from the crowd on fouls", and
that conclusion is only reachable from a settled ledger.

The results payload shape is not documented and no results existed at the time
this was written, so field names are probed rather than assumed and anything
unrecognised is reported rather than silently skipped.
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bot.ledger import Ledger, family_report, render_report  # noqa: E402
from bot.sportspredict.api import SportsPredictClient, SportsPredictError  # noqa: E402
from bot.sportspredict.config import Config, ConfigError  # noqa: E402

LESSONS_FILE = Path(__file__).resolve().parent.parent / "docs" / "LESSONS.md"

#: Field names the API might use, most specific first.  Probed rather than
#: assumed because the payload shape was not observable when this was written.
_MARKET_KEYS = ("market_id", "marketId", "market", "question_id", "id")
_OUTCOME_KEYS = ("outcome", "result", "settled_outcome", "resolution", "answer")
_CROWD_KEYS = ("crowd_probability", "crowd", "consensus", "average_probability", "mean_probability")


def _first(payload: dict[str, Any], keys: tuple[str, ...]) -> Any:
    for key in keys:
        if key in payload and payload[key] is not None:
            return payload[key]
    return None


def _as_outcome(value: Any) -> int | None:
    """Map whatever 'it happened' looks like onto 1 or 0."""
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (int, float)):
        return int(value) if value in (0, 1) else None
    if isinstance(value, str):
        text = value.strip().lower()
        if text in {"yes", "true", "won", "win", "1", "hit"}:
            return 1
        if text in {"no", "false", "lost", "lose", "0", "miss"}:
            return 0
    return None


def _as_probability(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    if number > 1.0:
        number /= 100.0
    return number if 0.0 <= number <= 1.0 else None


def settle(client: SportsPredictClient, ledger: Ledger, lobby_id: str) -> dict[str, int]:
    """Attach outcomes and crowd probabilities to every recorded prediction."""
    results = client.list_results(lobby_id)
    outcomes: dict[str, int] = {}
    crowd: dict[str, float] = {}
    unrecognised = 0

    for row in results:
        market_id = _first(row, _MARKET_KEYS)
        if isinstance(market_id, dict):
            market_id = market_id.get("id")
        outcome = _as_outcome(_first(row, _OUTCOME_KEYS))
        if market_id is None or outcome is None:
            unrecognised += 1
            continue
        outcomes[str(market_id)] = outcome
        value = _as_probability(_first(row, _CROWD_KEYS))
        if value is not None:
            crowd[str(market_id)] = value

    settled = 0
    for record in ledger.all_records():
        mine = {e.market_id for e in record.entries}
        subset = {k: v for k, v in outcomes.items() if k in mine}
        if subset:
            settled += ledger.settle(record.match_id, subset, crowd)

    return {
        "results_rows": len(results),
        "recognised": len(outcomes),
        "with_crowd": len(crowd),
        "unrecognised": unrecognised,
        "settled": settled,
    }


def write_lessons(ledger: Ledger, path: Path = LESSONS_FILE) -> Path:
    """Write the per-family scorecard and the actions it implies."""
    records = ledger.all_records()
    report = family_report(records)
    settled = sum(len(r.settled) for r in records)

    lines = [
        "# Lessons",
        "",
        "Generated by `scripts/settle.py --lessons`.  Do not edit by hand: it is",
        "rewritten on every settlement.",
        "",
        f"Updated {datetime.now(UTC).strftime('%Y-%m-%d %H:%M')}Z  |  "
        f"{len(records)} matches, {settled} settled questions",
        "",
        "## Per-family scorecard",
        "",
        "```",
        render_report(report),
        "```",
        "",
        "`beat%` is the share of questions where we beat the crowd.  It matters more",
        "than total RBP: a family can look profitable on one lucky match while losing",
        "more often than it wins, and that is a family to stop trusting rather than to",
        "scale up.",
        "",
        "## What to do about it",
        "",
    ]

    if not report:
        lines.append("Nothing settled yet.")
    else:
        for family, row in sorted(report.items(), key=lambda kv: kv[1]["total_rbp"]):
            lines.append(
                f"- **{family}** ({row['n']} settled, {row['total_rbp']:+.0f} RBP, "
                f"{100 * row['beat_crowd']:.0f}% beat crowd): {_verdict(row)}"
            )

    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _verdict(row: dict[str, float]) -> str:
    """Turn a family's record into the action it implies.

    Deliberately cautious about small samples. One round is a handful of
    questions per family, and reacting to that is how you tune against noise.
    """
    n, beat, total = row["n"], row["beat_crowd"], row["total_rbp"]
    if n < 20:
        return f"only {n:.0f} settled, too few to act on; keep pricing as is"
    if beat >= 0.60 and total > 0:
        return "beating the crowd consistently; this is where the edge is"
    if beat <= 0.40 and total < 0:
        return (
            "the crowd is beating us more often than not; move toward the crowd "
            "or the base rate rather than trying to model harder"
        )
    if total < 0:
        return "losing overall despite a fair hit rate; check for a few large misses"
    return "roughly level with the crowd; no strong signal either way"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lessons", action="store_true", help="rewrite docs/LESSONS.md")
    parser.add_argument("--offline", action="store_true", help="skip the API, report the ledger")
    args = parser.parse_args(argv)

    ledger = Ledger()

    if not args.offline:
        try:
            config = Config.from_env()
        except ConfigError as exc:
            print(f"config error: {exc}", file=sys.stderr)
            return 2
        client = SportsPredictClient(config)
        try:
            _, lobby = client.bootstrap()
            summary = settle(client, ledger, str(lobby["id"]))
        except SportsPredictError as exc:
            print(f"api error: {exc}", file=sys.stderr)
            return 2
        print(" ".join(f"{k}={v}" for k, v in summary.items()))
        if summary["unrecognised"]:
            print(
                f"  ! {summary['unrecognised']} result rows had no recognisable market id "
                "or outcome; the payload shape may have changed",
                file=sys.stderr,
            )
        if summary["recognised"] and not summary["with_crowd"]:
            print(
                "  ! outcomes arrived but no crowd probability. RBP cannot be computed "
                "without it, so scores will stay empty until the field is identified.",
                file=sys.stderr,
            )

    print()
    print(render_report(family_report(ledger.all_records())))

    if args.lessons:
        print(f"\nwrote {write_lessons(ledger)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
